-- 6. GÉNÉRATION DE 600 JOUEURS (DÉBUTANT À DIAMANT) POUR L'ENTRAÎNEMENT OML
-- ============================================================================
DECLARE
    v_rang      VARCHAR2(40);
    v_hs_base   NUMBER;
    v_body_base NUMBER;
    v_adr_base  NUMBER;
    v_kd_base   NUMBER;
    v_kast_base NUMBER;
    v_dd_base   NUMBER;
    v_head_pct  NUMBER;
    v_body_pct  NUMBER;
    v_leg_pct   NUMBER;
    v_riot_id   VARCHAR2(80);
BEGIN
    FOR palier IN 1..6 LOOP
        CASE palier
            WHEN 1 THEN v_rang := '1 - Débutant (Niv 1-20)'; v_hs_base := 10; v_body_base := 79; v_adr_base := 102; v_kd_base := 0.82; v_kast_base := 63; v_dd_base := -18;
            WHEN 2 THEN v_rang := '2 - Fer';                 v_hs_base := 13; v_body_base := 76; v_adr_base := 115; v_kd_base := 0.91; v_kast_base := 66; v_dd_base := -10;
            WHEN 3 THEN v_rang := '3 - Bronze';              v_hs_base := 17; v_body_base := 73; v_adr_base := 126; v_kd_base := 0.98; v_kast_base := 69; v_dd_base := -3;
            WHEN 4 THEN v_rang := '4 - Argent';              v_hs_base := 21; v_body_base := 70; v_adr_base := 136; v_kd_base := 1.05; v_kast_base := 72; v_dd_base := 3;
            WHEN 5 THEN v_rang := '5 - Or';                  v_hs_base := 25; v_body_base := 67; v_adr_base := 145; v_kd_base := 1.12; v_kast_base := 74; v_dd_base := 10;
            WHEN 6 THEN v_rang := '6 - Platine+';            v_hs_base := 30; v_body_base := 63; v_adr_base := 158; v_kd_base := 1.22; v_kast_base := 77; v_dd_base := 18;
        END CASE;

        FOR i IN 1..100 LOOP
            v_riot_id := 'Player_' || palier || '_' || i || '#EUW';
            v_head_pct := ROUND(GREATEST(4, LEAST(55, v_hs_base + DBMS_RANDOM.NORMAL * 2.8)), 1);
            v_body_pct := ROUND(GREATEST(35, LEAST(90 - v_head_pct, v_body_base + DBMS_RANDOM.NORMAL * 3.5)), 1);
            v_leg_pct  := ROUND(100 - v_head_pct - v_body_pct, 1);

            INSERT INTO valo_joueurs (riot_id, type_profil, niveau_compte, rang_actuel)
            VALUES (v_riot_id, 'BENCHMARK', palier * 15 + MOD(i, 12), v_rang);

            INSERT INTO valo_matchs_stats (
                match_id, riot_id, mode_jeu, carte, agent, role_agent,
                score_equipe, score_ennemi, victoire, kills, deaths, assists,
                kd_ratio, kad_ratio, adr, acs, kast_pct, dd_delta, kills_per_round,
                first_bloods, flawless_rounds, aces, head_hits, body_hits, leg_hits,
                head_pct, body_pct, leg_pct, rang_cible_ml
            ) VALUES (
                'BENCH_M_' || palier || '_' || i, v_riot_id, 'Competitive',
                CASE MOD(i, 4) WHEN 0 THEN 'Corrode' WHEN 1 THEN 'Ascent' WHEN 2 THEN 'Bind' ELSE 'Haven' END,
                CASE MOD(i, 4) WHEN 0 THEN 'Sage' WHEN 1 THEN 'Chamber' WHEN 2 THEN 'Jett' ELSE 'Reyna' END,
                CASE MOD(i, 2) WHEN 0 THEN 'Sentinel' ELSE 'Duelist' END,
                13, 9, CASE WHEN MOD(i, 2) = 0 THEN 1 ELSE 0 END,
                12 + palier, 14, 5,
                ROUND(GREATEST(0.3, v_kd_base + DBMS_RANDOM.NORMAL * 0.12), 2),
                ROUND(GREATEST(0.5, v_kd_base + 0.3 + DBMS_RANDOM.NORMAL * 0.12), 2),
                ROUND(v_adr_base + DBMS_RANDOM.NORMAL * 10, 1),
                ROUND((v_adr_base + DBMS_RANDOM.NORMAL * 10) * 1.48, 1),
                ROUND(GREATEST(45, LEAST(95, v_kast_base + DBMS_RANDOM.NORMAL * 4)), 1),
                ROUND(v_dd_base + DBMS_RANDOM.NORMAL * 7, 0),
                ROUND(0.55 + palier * 0.05, 2),
                MOD(i, 4), MOD(i, 2), 0,
                ROUND(v_head_pct * 2), ROUND(v_body_pct * 2), ROUND(v_leg_pct * 2),
                v_head_pct, v_body_pct, v_leg_pct, v_rang
            );
        END LOOP;
    END LOOP;
    COMMIT;
END;
