-- ============================================================================
-- 2. TABLE DES PROFILS JOUEURS (Toi + Joueurs aspirés + Base d'entraînement)
-- ============================================================================
CREATE TABLE valo_joueurs (
    riot_id          VARCHAR2(80) PRIMARY KEY,
    type_profil      VARCHAR2(30) DEFAULT 'JOUEUR_MATCHMAKING', -- 'MON_COMPTE', 'JOUEUR_MATCHMAKING', 'BENCHMARK'
    niveau_compte    NUMBER(5),
    rang_actuel      VARCHAR2(40),
    derniere_maj     TIMESTAMP DEFAULT SYSTIMESTAMP
);

-- ============================================================================
-- 3. TABLE DES MATCHS & AGENTS (Alimente Overview, Silhouette & Top Agents)
-- ============================================================================
CREATE TABLE valo_matchs_stats (
    id_perf          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id         VARCHAR2(80),
    riot_id          VARCHAR2(80) REFERENCES valo_joueurs(riot_id),
    date_match       TIMESTAMP DEFAULT SYSTIMESTAMP,
    mode_jeu         VARCHAR2(30),
    carte            VARCHAR2(40),
    agent            VARCHAR2(40),
    role_agent       VARCHAR2(30),
    score_equipe     NUMBER(3),
    score_ennemi     NUMBER(3),
    victoire         NUMBER(1), -- 1 = Win, 0 = Loss
    kills            NUMBER(4),
    deaths           NUMBER(4),
    assists          NUMBER(4),
    kd_ratio         NUMBER(5,2),
    kad_ratio        NUMBER(5,2),
    adr              NUMBER(6,1),
    acs              NUMBER(6,1),
    kast_pct         NUMBER(5,1),
    dd_delta         NUMBER(5),
    kills_per_round  NUMBER(4,2),
    first_bloods     NUMBER(3),
    flawless_rounds  NUMBER(3),
    aces             NUMBER(2),
    head_hits        NUMBER(5),
    body_hits        NUMBER(5),
    leg_hits         NUMBER(5),
    head_pct         NUMBER(5,1),
    body_pct         NUMBER(5,1),
    leg_pct          NUMBER(5,1),
    rang_cible_ml    VARCHAR2(40)
);

-- ============================================================================
-- 4. TABLE DES STATS PAR ARME (Alimente Top Weapons : Vandal, Sheriff, Classic)
-- ============================================================================
CREATE TABLE valo_stats_armes (
    id_stat_arme     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    riot_id          VARCHAR2(80) REFERENCES valo_joueurs(riot_id),
    nom_arme         VARCHAR2(50) REFERENCES kaggle_ref_armes(nom_arme),
    kills            NUMBER(5),
    head_pct         NUMBER(5,1),
    body_pct         NUMBER(5,1),
    leg_pct          NUMBER(5,1),
    adr_arme         NUMBER(6,1),
     CONSTRAINT uk_joueur_arme UNIQUE (riot_id, nom_arme)
);

