ALTER TABLE valo_matchs_stats ADD (saison VARCHAR2(10));

CREATE TABLE valo_mmr_history (
    id_mmr        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    riot_id       VARCHAR2(80) REFERENCES valo_joueurs(riot_id),
    match_id      VARCHAR2(80),
    date_match    TIMESTAMP,
    carte         VARCHAR2(40),
    saison        VARCHAR2(10),
    tier_id       NUMBER(3),
    tier_nom      VARCHAR2(30),
    elo           NUMBER(6),
    rr            NUMBER(4),
    variation_rr  NUMBER(4),
    CONSTRAINT uk_mmr_joueur_match UNIQUE (riot_id, match_id)
);

EXIT;
